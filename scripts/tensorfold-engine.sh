#!/usr/bin/env bash
# TensorFold engine launcher for the DGX Spark pair: build the engine image on the head, copy it to the worker,
# and report what each node holds. This is the engine half of the separate DSv4.1 stack; the model half is
# scripts/tensorfold-model.sh. Neither touches the vLLM stack (miaai / b12x engines).
#
#   scripts/tensorfold-engine.sh build [profile]     # build + copy + compare image IDs
#   scripts/tensorfold-engine.sh status [profile]    # image ID per node, container state
#   scripts/tensorfold-engine.sh doctor [profile]    # preflight without starting anything
#   scripts/tensorfold-engine.sh env [profile]       # print the generated settings file path
#
# The recipe lives in $SPARK_TENSORFOLD_RECIPE (default ~/ds41-recipe) on branch podman-support:
# https://github.com/kambiz-aghaiepour/DeepSeek-V4.1-Flash-1017-EXL3-TensorFold-2x-DGX-Spark
# Container runtime is podman here (CONTAINER_RT=podman, rootful by default: the recipe needs the
# tensorfold.slice cgroup, /dev/infiniband and memlock the way docker gives them).
set -euo pipefail

HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
REPO_ROOT="$(cd "$HERE/.." && pwd)"
RECIPE_DIR=${SPARK_TENSORFOLD_RECIPE:-$HOME/ds41-recipe}
RECIPE_REPO=${SPARK_TENSORFOLD_REPO:-https://github.com/kambiz-aghaiepour/DeepSeek-V4.1-Flash-1017-EXL3-TensorFold-2x-DGX-Spark.git}
RECIPE_BRANCH=${SPARK_TENSORFOLD_BRANCH:-podman-support}
CONF_DIR=${SPARK_TENSORFOLD_CONF:-$HOME/.config/spark-vllm/tensorfold}
CLUSTER_ENV=${SPARK_TENSORFOLD_CLUSTER:-$CONF_DIR/cluster.env}
DEFAULT_PROFILE=dealign-direct

die() { echo "tensorfold-engine: $*" >&2; exit 1; }
log() { echo "[tf-engine $(date -u +%H:%M:%SZ)] $*"; }

usage() { sed -n '2,16p' "${BASH_SOURCE[0]}" | sed 's/^# \{0,1\}//'; }

cmd=${1:-}; [ -n "$cmd" ] || { usage; exit 2; }
shift || true
case "$cmd" in -h|--help) usage; exit 0 ;; esac
profile=${1:-$DEFAULT_PROFILE}

ensure_recipe() {
  if [ ! -d "$RECIPE_DIR/.git" ]; then
    [ -e "$RECIPE_DIR" ] && die "$RECIPE_DIR exists but is not a git checkout; move it away or set SPARK_TENSORFOLD_RECIPE"
    log "cloning $RECIPE_REPO ($RECIPE_BRANCH) -> $RECIPE_DIR"
    git clone -q --branch "$RECIPE_BRANCH" "$RECIPE_REPO" "$RECIPE_DIR"
  else
    local branch
    branch=$(git -C "$RECIPE_DIR" rev-parse --abbrev-ref HEAD)
    if [ "$branch" != "$RECIPE_BRANCH" ]; then
      log "switching $RECIPE_DIR from $branch to $RECIPE_BRANCH"
      git -C "$RECIPE_DIR" fetch -q origin "$RECIPE_BRANCH"
      git -C "$RECIPE_DIR" checkout -q "$RECIPE_BRANCH"
    fi
    if git -C "$RECIPE_DIR" rev-parse --abbrev-ref --symbolic-full-name '@{u}' >/dev/null 2>&1; then
      git -C "$RECIPE_DIR" pull -q --ff-only 2>/dev/null || log "warning: could not fast-forward $RECIPE_DIR (local edits?)"
    fi
  fi
  [ -x "$RECIPE_DIR/start.sh" ] || die "$RECIPE_DIR does not look like the recipe (no start.sh)"
}

# Build the settings file the recipe reads: cluster settings + the model profile, with the runtime pinned to podman.
write_env() {
  [ -f "$CLUSTER_ENV" ] || die "missing $CLUSTER_ENV (copy config/tensorfold/cluster.env.example there)"
  local profile_file
  if [ -f "$REPO_ROOT/config/tensorfold/$profile.env" ]; then
    profile_file="$REPO_ROOT/config/tensorfold/$profile.env"
  elif [ -f "$CONF_DIR/profiles/$profile.env" ]; then
    profile_file="$CONF_DIR/profiles/$profile.env"
  else
    die "unknown profile '$profile' (looked in config/tensorfold/ and $CONF_DIR/profiles/)"
  fi
  mkdir -p "$CONF_DIR/profiles"
  local out="$CONF_DIR/profiles/$profile.env"
  {
    echo "# generated by scripts/tensorfold-engine.sh from $profile_file - do not edit"
    echo "# cluster settings"
    cat "$CLUSTER_ENV"
    echo
    echo "# model profile: $profile"
    cat "$profile_file"
  } > "$out"
  printf '%s\n' "$out"
}

case "$cmd" in
  env)
    ensure_recipe; write_env
    ;;
  build)
    ensure_recipe
    env_file=$(write_env)
    log "building the engine image (podman, rootful) from profile $profile"
    TF_ENV_FILE="$env_file" "$RECIPE_DIR/docker/build.sh"
    ;;
  status)
    ensure_recipe
    env_file=$(write_env)
    # shellcheck source=/dev/null
    TF_ENV_FILE="$env_file" bash -c '. "$TF_ENV_FILE"; echo "image:   $IMAGE"; echo "recipe:  $TF_REPO @ $TF_COMMIT"'
    # shellcheck source=/dev/null
    TF_ENV_FILE="$env_file" bash -c '. "$TF_ENV_FILE"
      echo -n "head:    "; sudo -n podman images "$IMAGE" --format "{{.ID}} {{.CreatedSince}}" 2>/dev/null || echo "no image"
      echo -n "worker:  "; ssh -n -o BatchMode=yes -o ConnectTimeout=10 "$WORKER_SSH" "sudo -n podman images \"$IMAGE\" --format \"{{.ID}} {{.CreatedSince}}\"" 2>/dev/null || echo "unreachable or no image"
      echo -n "ranks:   "; sudo -n podman ps -a --format "{{.Names}} {{.Status}}" 2>/dev/null | grep tfv41 | tr "\n" " " ; echo
      echo -n "worker ranks: "; ssh -n -o BatchMode=yes -o ConnectTimeout=10 "$WORKER_SSH" "sudo -n podman ps -a --format \"{{.Names}} {{.Status}}\"" 2>/dev/null | grep tfv41 | tr "\n" " "; echo'
    ;;
  doctor)
    ensure_recipe
    env_file=$(write_env)
    log "preflight from the recipe (nothing is started)"
    TF_ENV_FILE="$env_file" "$RECIPE_DIR/scripts/preflight.sh" || true
    ;;
  *)
    usage; exit 2
    ;;
esac
