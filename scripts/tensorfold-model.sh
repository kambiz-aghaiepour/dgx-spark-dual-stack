#!/usr/bin/env bash
# TensorFold model launcher: fetch a model view, start/stop the server, and read its state. This is the model half
# of the separate DSv4.1 stack; the engine half is scripts/tensorfold-engine.sh.
#
#   scripts/tensorfold-model.sh fetch  [profile]   # download + build the model view (+ worker copy)
#   scripts/tensorfold-model.sh start  [profile]   # preflight, extension build, two ranks, wait for the API
#   scripts/tensorfold-model.sh stop   [profile]   # stop both ranks, save their logs
#   scripts/tensorfold-model.sh status [profile]   # ranks + API
#   scripts/tensorfold-model.sh verify [profile]   # five real requests against the API
#   scripts/tensorfold-model.sh logs   [profile]   # last 80 lines of each rank
#
# Profiles live in config/tensorfold/<name>.env (base, dealign-direct, dealign-bf16). Cluster settings
# (node addresses, RoCE names) live in ~/.config/spark-vllm/tensorfold/cluster.env.
#
# One server at a time: this stack needs ~100 GiB of memory per node, so the launcher refuses to start while the
# vLLM stack serves, and the vLLM stack must not be started while this one runs.
set -euo pipefail

HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
REPO_ROOT="$(cd "$HERE/.." && pwd)"
RECIPE_DIR=${SPARK_TENSORFOLD_RECIPE:-$HOME/ds41-recipe}
RECIPE_REPO=${SPARK_TENSORFOLD_REPO:-https://github.com/kambiz-aghaiepour/DeepSeek-V4.1-Flash-1017-EXL3-TensorFold-2x-DGX-Spark.git}
RECIPE_BRANCH=${SPARK_TENSORFOLD_BRANCH:-podman-support}
CONF_DIR=${SPARK_TENSORFOLD_CONF:-$HOME/.config/spark-vllm/tensorfold}
CLUSTER_ENV=${SPARK_TENSORFOLD_CLUSTER:-$CONF_DIR/cluster.env}
DEFAULT_PROFILE=dealign-direct
VLLM_URL=${SPARK_VLLM_ENGINE_URL:-http://127.0.0.1:8000}

die() { echo "tensorfold-model: $*" >&2; exit 1; }
log() { echo "[tf-model $(date -u +%H:%M:%SZ)] $*"; }
usage() { sed -n '2,18p' "${BASH_SOURCE[0]}" | sed 's/^# \{0,1\}//'; }

cmd=${1:-}; [ -n "$cmd" ] || { usage; exit 2; }
shift || true
case "$cmd" in -h|--help) usage; exit 0 ;; esac
profile=${1:-$DEFAULT_PROFILE}

ensure_recipe() {
  if [ ! -d "$RECIPE_DIR/.git" ]; then
    [ -e "$RECIPE_DIR" ] && die "$RECIPE_DIR exists but is not a git checkout; move it away or set SPARK_TENSORFOLD_RECIPE"
    log "cloning $RECIPE_REPO ($RECIPE_BRANCH) -> $RECIPE_DIR"
    git clone -q --branch "$RECIPE_BRANCH" "$RECIPE_REPO" "$RECIPE_DIR"
  fi
  [ -x "$RECIPE_DIR/start.sh" ] || die "$RECIPE_DIR does not look like the recipe (no start.sh)"
}

write_env() {
  [ -f "$CLUSTER_ENV" ] || die "missing $CLUSTER_ENV (copy config/tensorfold/cluster.env.example there)"
  local profile_file=""
  if [ -f "$REPO_ROOT/config/tensorfold/$profile.env" ]; then
    profile_file="$REPO_ROOT/config/tensorfold/$profile.env"
  elif [ -f "$CONF_DIR/profiles/$profile.env" ]; then
    profile_file="$CONF_DIR/profiles/$profile.env"
  else
    die "unknown profile '$profile' (looked in config/tensorfold/ and $CONF_DIR/profiles/)"
  fi
  mkdir -p "$CONF_DIR/profiles"
  local out="$CONF_DIR/profiles/$profile.env"
  {
    echo "# generated by scripts/tensorfold-model.sh from $profile_file - do not edit"
    echo "# cluster settings"
    cat "$CLUSTER_ENV"
    echo
    echo "# model profile: $profile"
    cat "$profile_file"
  } > "$out"
  printf '%s\n' "$out"
}

vllm_serving() {
  # The unit and the container are the ground truth; the port alone can be something else.
  systemctl --user is-active --quiet spark-vllm-podman 2>/dev/null && return 0
  command -v podman >/dev/null 2>&1 || return 1
  podman ps --format '{{.Names}}' 2>/dev/null | grep -qx vllm-fn && return 0
  sudo -n podman ps --format '{{.Names}}' 2>/dev/null | grep -qx vllm-fn && return 0
  return 1
}

refuse_if_vllm() {
  [ "${SPARK_TENSORFOLD_ALLOW_VLLM:-0}" = 1 ] && return 0
  if vllm_serving || (command -v podman >/dev/null && podman ps --format '{{.Names}}' 2>/dev/null | grep -qx vllm-fn); then
    die "the vLLM stack is serving ($VLLM_URL or container vllm-fn): stop it first (systemctl --user stop spark-vllm-podman), because one model server at a time fits in the memory"
  fi
}

# --------------------------------------------------------------------------------------------- fetch
# The direct dealignai bundle is one exllamav3 folder. The engine wants model/ and engram/ apart, so the
# shards are hard-linked into that layout (same disk, no second copy).
DEALIGN_REPO=dealignai/DeepSeek-V4.1-Flash-1017-EXL3-2.9bpw-UNCENSORED
DEALIGN_REV=89af9bf193575b7eeeb4f1dd85463ec24ea5bb4c

fetch_dealign_direct() {
  local env_file; env_file=$("$REPO_ROOT/scripts/tensorfold-engine.sh" env "$profile")
  # shellcheck source=/dev/null
  . "$env_file"
  : "${MODEL_VIEW:?profile must set MODEL_VIEW}"
  local dl="${DOWNLOAD_DIR:-$MODEL_VIEW.src}"
  mkdir -p "$dl" "$MODEL_VIEW/model" "$MODEL_VIEW/engram"
  local meta=(model.safetensors.index.json config.json exl3_k_map.json quantization_config.json
              tokenizer.json tokenizer_config.json)
  log "downloading $DEALIGN_REPO @ ${DEALIGN_REV:0:12} into $dl (~416 GB, resumable)"
  if command -v hf >/dev/null; then
    hf download "$DEALIGN_REPO" --revision "$DEALIGN_REV" --local-dir "$dl" || die "download failed; run the same command again to resume"
  else
    # No CLI: the same files straight from the CDN, resumed where they stopped.
    log "the 'hf' command is missing - using curl (installs nothing)"
    local auth=(); [ -n "${HF_TOKEN:-}" ] && auth=(-H "Authorization: Bearer $HF_TOKEN")
    local listing; listing=$(curl -fsSL "https://huggingface.co/api/models/$DEALIGN_REPO/tree/$DEALIGN_REV?recursive=true") \
      || die "cannot list $DEALIGN_REPO"
    want_size() {
      printf '%s' "$listing" | python3 -c 'import json,sys
p=sys.argv[1]
print(next((f["size"] for f in json.load(sys.stdin) if f["path"]==p), 0))' "$1"
    }
    local f i want have
    for f in $(for i in $(seq -w 1 43); do echo "model-000${i}-of-00043.safetensors"; done) \
             model-00047-of-00048.safetensors model-00048-of-00048.safetensors "${meta[@]}"; do
      want=$(want_size "$f"); [ "$want" -gt 0 ] || die "the repo does not list $f"
      have=$(stat -c %s "$dl/$f" 2>/dev/null || echo 0)
      if [ "$have" = "$want" ]; then log "have $f"; continue; fi
      log "get  $f ($((have/1048576)) of $((want/1048576)) MiB)"
      # http1.1: the CDN cancels HTTP/2 streams on these multi-GB shards; retry-all-errors covers the rest.
      curl -fL --http1.1 --retry 10 --retry-all-errors --retry-delay 3 -C - --create-dirs "${auth[@]}" \
        -o "$dl/$f" "https://huggingface.co/$DEALIGN_REPO/resolve/$DEALIGN_REV/$f" \
        || die "download of $f failed; run the same command again to resume"
      have=$(stat -c %s "$dl/$f" 2>/dev/null || echo 0)
      [ "$have" = "$want" ] || die "$f is incomplete ($have of $want bytes); run the same command again to resume"
    done
  fi
  log "building the view $MODEL_VIEW (hard links, no second copy)"
  local base
  for f in "$dl"/model-000[0-4][0-9]-of-00043.safetensors "${meta[@]/#/$dl/}"; do
    [ -e "$f" ] || continue
    base=$(basename "$f")
    [ -e "$MODEL_VIEW/model/$base" ] || ln "$f" "$MODEL_VIEW/model/$base"
  done
  for f in "$dl"/model-00047-of-00048.safetensors "$dl"/model-00048-of-00048.safetensors \
           "$dl"/model.safetensors.index.json "$dl"/config.json; do
    [ -e "$f" ] || { log "warning: $f not in the download"; continue; }
    base=$(basename "$f")
    [ -e "$MODEL_VIEW/engram/$base" ] || ln "$f" "$MODEL_VIEW/engram/$base"
  done
  local shards
  shards=$(find "$MODEL_VIEW/model" -name 'model-*-of-00043.safetensors' | wc -l)
  [ "$shards" -ge 43 ] || die "the view has $shards of 43 weight shards"
  log "view ready: $shards shards, $(du -sh "$MODEL_VIEW" 2>/dev/null | cut -f1)"
  log "copying the view to the worker ($WORKER_SSH); this reads ~385 GB"
  rsync -a --info=progress2 "$MODEL_VIEW/" "$WORKER_SSH:$MODEL_VIEW/" || die "rsync to the worker failed"
  log "chat template (MiaAI patch, both nodes)"
  "$RECIPE_DIR/scripts/patch_template.py" --worker || die "chat template step failed"
  log "fetch done. Next: scripts/tensorfold-model.sh start $profile"
}

# --------------------------------------------------------------------------------------------- actions
ensure_recipe
env_file=$(write_env)
export TF_ENV_FILE="$env_file"

case "$cmd" in
  env)   echo "$env_file" ;;
  fetch)
    case "$profile" in
      base) log "base profile: the recipe's own downloader (LibertAI pack + engram shards)"; ( cd "$RECIPE_DIR" && ./scripts/download.sh ) ;;
      dealign-direct) fetch_dealign_direct ;;
      *) die "profile '$profile' has no fetch step (see docs/tensorfold.md)" ;;
    esac
    ;;
  start)  refuse_if_vllm; ( cd "$RECIPE_DIR" && ./start.sh ) ;;
  stop)   ( cd "$RECIPE_DIR" && ./stop.sh ) ;;
  status) ( cd "$RECIPE_DIR" && ./status.sh ) ;;
  verify) ( cd "$RECIPE_DIR" && ./verify.sh ) ;;
  logs)
    # shellcheck source=/dev/null
    . "$env_file"
    echo "== head (tfv41-r0) =="; sudo -n podman logs --tail 80 tfv41-r0 2>&1 || true
    echo "== worker (tfv41-r1) =="; ssh -n -o BatchMode=yes "$WORKER_SSH" 'sudo -n podman logs --tail 80 tfv41-r1' 2>&1 || true
    ;;
  *) usage; exit 2 ;;
esac
